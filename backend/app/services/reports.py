"""Generate owner-scoped research reports from FinSight's sourced data.

A report is a snapshot: figures, their provenance (reported / calculated / assumption /
extracted / market / AI explanation), sources and timestamps as of generation. Sections whose
data is missing are included as ``unavailable`` with the reason, never filled in.
"""

