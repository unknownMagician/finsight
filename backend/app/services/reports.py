MAX_REPORTS_PER_USER = 100
STATEMENT_ROWS = (
    ("income", "revenue", "Revenue"),
    ("income", "operating_income", "Operating profit (EBIT)"),
    ("income", "net_income", "Net profit"),
    ("income", "diluted_eps", "Diluted EPS (₹)"),
    ("balance", "total_assets", "Total assets"),
    ("balance", "total_equity", "Shareholders' equity"),
    ("balance", "total_debt", "Total debt (reported)"),
    ("balance", "cash_and_equivalents", "Cash & equivalents"),
    ("cash_flow", "operating_cash_flow", "Operating cash flow"),
    ("cash_flow", "capital_expenditures", "Capital expenditure"),
)
RATIO_KEYS = (
    "revenue_growth",
    "net_income_growth",
    "operating_margin",
    "net_margin",
    "return_on_equity",
    "return_on_capital_employed",
    "debt_to_equity",
    "interest_coverage",
    "free_cash_flow",
)
VALUATION_KEYS = (
    "market_cap",
    "enterprise_value",
    "price_to_earnings",
    "price_to_book",
    "ev_to_ebitda",
    "dividend_yield",
)
AI_QUESTION = (
    "Summarize the company's latest reported financial performance, financial position and the "
    "main risks stated in the sources. Cite every figure."
)
DISCLAIMERS = [
    "Generated by FinSight from the sources named in each section. Figures are labelled "
    "reported, calculated, assumption, extracted, market data or AI explanation.",
    "Prices are end-of-day closes (not real-time) and are not adjusted for splits or bonuses.",
    "Missing data is shown as unavailable and is never estimated.",
    "This report is not investment advice.",
]


def _metric_display(unit: str, value: Decimal, scale: Scale) -> str:
    if unit == "ratio":
        return percent(value)
    if unit == "times":
        return times(value)
    return crores(rescale(value, scale, Scale.CRORES))


def _unavailable(key: str, title: str, reason: str) -> ReportSection:
    return ReportSection(key=key, title=title, status="unavailable", reason=reason)


def _profile(company: Company) -> ReportSection:
    rows = [
        [
            i.exchange,
            i.symbol,
            i.series or "—",
            i.listing_status,
            str(i.last_traded_on or "—"),
            i.provider,
        ]
        for i in sorted(company.instruments, key=lambda i: i.exchange)
    ]
    return ReportSection(
        key="profile",
        title="Company and listings",
        paragraphs=[
            f"{company.name} ({company.ticker})"
            + (f", ISIN {company.isin}" if company.isin else ", ISIN not provided by the source")
            + "."
        ],
        tables=[
            ReportTable(
                caption="Exchange listings",
                kind="market",
                columns=["Exchange", "Symbol", "Series", "Status", "Last traded", "Source"],
                rows=rows,
            )
        ]
        if rows
        else [],
    )


def _market(
    provider: MarketDataProvider,
    cache: TTLCache,
    company: Company,
    exchange: str | None,
    *,
    stale_after_days: int,
    today: date,
) -> tuple[ReportSection, str | None]:
    title = "Market data (end of day)"
    try:
        instrument = resolve_listing(company, exchange)
        quote = market_data.latest_quote(
            provider, cache, instrument, stale_after_days=stale_after_days, today=today
        )
        history = market_data.price_history(
            provider,
            cache,
            instrument,
            today - timedelta(days=365),
            today,
            stale_after_days=stale_after_days,
            today=today,
        )
    except AppError as exc:
        return _unavailable("market", title, exc.message), exchange
    series = quote.series
    source = (
        f"{series.provider} ({series.nature}), retrieved {series.retrieved_at:%Y-%m-%d %H:%M} UTC"
    )
    figures = [
        ReportFigure(
            label=f"Close, {instrument.exchange}: {instrument.symbol}",
            value=quote.bar.close,
            display=inr(quote.bar.close),
            kind="market",
            period=str(quote.bar.date),
            source=source,
            note="stale: older than the freshness threshold" if quote.stale else None,
        )
    ]
    bars = history.series.bars
    if len(bars) >= 2 and bars[0].close > 0:
        change = bars[-1].close / bars[0].close - 1
        figures.append(
            ReportFigure(
                label="Price change over the period",
                value=change,
                display=percent(change),
                kind="calculated",
                period=f"{bars[0].date} to {bars[-1].date}",
                source=source,
                note="raw closes, not adjusted for corporate actions",
            )
        )
    return ReportSection(key="market", title=title, figures=figures), instrument.exchange


def _financials(db: Session, company: Company, basis: ReportingBasis) -> ReportSection:
    periods = company_service.annual_periods(db, company, basis)
    years = sorted(periods, reverse=True)[:5]
    columns = ["Item (₹ crore unless stated)", *[f"FY{str(y)[-2:]}" for y in years]]
    rows = []
    for statement, item, label in STATEMENT_ROWS:
        row = [label]
        for year in years:
            period = periods[year]
            line = next(
                (li for li in period.line_items if li.statement == statement and li.item == item),
                None,
            )
            if line is None:
                row.append("—")
            elif item == "diluted_eps":
                row.append(indian_group(Decimal(line.value)))
            else:
                row.append(
                    indian_group(rescale(Decimal(line.value), Scale(period.scale), Scale.CRORES))
                )
        rows.append(row)
    latest = periods[years[0]]
    return ReportSection(
        key="financials",
        title=f"Financial statements ({basis})",
        paragraphs=["“—” means the source did not report the item; it is not zero."],
        tables=[
            ReportTable(
                caption=f"Annual figures, {basis}",
                kind="reported",
                columns=columns,
                rows=rows,
                source=f"{latest.source_provider}, retrieved {latest.retrieved_at:%Y-%m-%d}",
            )
        ],
    )


def _ratios(db: Session, company: Company, basis: ReportingBasis) -> ReportSection:
    title = "Ratios"
    try:
        report = company_service.ratios(db, company, None, basis)
    except AppError as exc:
        return _unavailable("ratios", title, exc.message)
    figures = []
    for key in RATIO_KEYS:
        metric = report.metrics.get(key)
        if metric is None:
            continue
        ok = metric.status == "ok" and metric.value is not None
        figures.append(
            ReportFigure(
                label=metric.name,
                value=metric.value if ok else None,
                display=_metric_display(metric.unit, metric.value, report.scale)
                if ok and metric.value is not None
                else "—",
                kind="calculated",
                period=f"FY{report.period.fiscal_year}",
                basis=report.basis,
                source=metric.formula,
                note=None if ok else (metric.note or f"missing: {', '.join(metric.missing)}"),
            )
        )
    return ReportSection(key="ratios", title=title, figures=figures)


def _valuation(
    db: Session,
    provider: MarketDataProvider,
    cache: TTLCache,
    company: Company,
    exchange: str | None,
    basis: ReportingBasis,
    *,
    stale_after_days: int,
    today: date,
) -> ReportSection:
    title = "Valuation multiples"
    try:
        snap = market_data.valuation_snapshot(
            db,
            provider,
            cache,
            company,
            exchange=exchange,
            basis=basis,
            stale_after_days=stale_after_days,
            today=today,
        )
    except AppError as exc:
        return _unavailable("valuation", title, exc.message)
    r = snap.report
    figures = []
    for key in VALUATION_KEYS:
        metric = r.metrics.get(key)
        if metric is None:
            continue
        ok = metric.status == "ok" and metric.value is not None
        figures.append(
            ReportFigure(
                label=metric.name,
                value=metric.value if ok else None,
                display=_metric_display(metric.unit, metric.value, r.scale)
                if ok and metric.value is not None
                else "—",
                kind="calculated",
                period=f"close {r.price.price_date} x FY{r.period.fiscal_year}",
                basis=snap.basis,
                source=metric.formula,
                note=None if ok else metric.note,
            )
        )
    return ReportSection(
        key="valuation", title=title, figures=figures, paragraphs=[i.message for i in r.issues]
    )


def _actions(provider: MarketDataProvider, cache: TTLCache, company: Company) -> ReportSection:
    title = "Corporate actions"
    try:
        result = market_data.corporate_actions(provider, cache, company)
    except AppError as exc:
        return _unavailable("actions", title, exc.message)
    if not result.actions:
        return _unavailable("actions", title, f"no corporate actions reported by {result.provider}")
    rows = [
        [
            str(a.ex_date),
            a.exchange,
            a.action_type,
            inr(a.cash_amount) if a.cash_amount is not None else "—",
            a.description,
        ]
        for a in result.actions[:12]
    ]
    return ReportSection(
        key="actions",
        title=title,
        tables=[
            ReportTable(
                caption="Most recent corporate actions",
                kind="reported",
                columns=["Ex-date", "Exchange", "Type", "Cash per share", "Announcement"],
                rows=rows,
                source=f"{result.provider}, retrieved {result.retrieved_at:%Y-%m-%d}",
            )
        ],
    )


def _documents(db: Session, owner: User, company: Company) -> ReportSection:
    title = "Figures from uploaded reports"
    documents = list(
        db.scalars(
            select(Document)
            .where(Document.owner_id == owner.id, Document.company_id == company.id)
            .options(selectinload(Document.facts))
        )
    )
    rows = [
        [d.title, f.metric, indian_group(f.value), f.unit, f.basis, f"p. {f.page_number}", f.quote]
        for d in documents
        for f in d.facts
        if f.status == "verified"
    ]
    if not rows:
        return _unavailable(
            "documents", title, "no verified figures extracted from your uploaded reports"
        )
    return ReportSection(
        key="documents",
        title=title,
        paragraphs=["Only figures verified against the page text are included."],
        tables=[
            ReportTable(
                caption="Verified extracted figures",
                kind="extracted",
                columns=["Document", "Metric", "Value", "Unit", "Basis", "Page", "Quote"],
                rows=rows,
            )
        ],
    )


def _valuations(db: Session, owner: User, company: Company) -> ReportSection:
    title = "Your saved DCF valuations"
    saved = list(
        db.scalars(
            select(SavedValuation)
            .where(SavedValuation.owner_id == owner.id, SavedValuation.company_id == company.id)
            .order_by(SavedValuation.created_at.desc())
            .limit(5)
        )
    )
    if not saved:
        return _unavailable("dcf", title, "no saved valuations for this company")
    rows = []
    for v in saved:
        result, inputs = v.result, v.inputs
        terminal = (
            f"g {percent(Decimal(inputs['terminal_growth']))}"
            if inputs.get("terminal_growth")
            else f"{inputs.get('exit_multiple')}x EBITDA"
        )
        per_share = result.get("value_per_share")
        rows.append(
            [
                v.name,
                f"{v.created_at:%Y-%m-%d}",
                percent(Decimal(inputs["wacc"])),
                terminal,
                inr(Decimal(per_share)) if per_share else "—",
            ]
        )
    return ReportSection(
        key="dcf",
        title=title,
        paragraphs=["Results of your own assumptions; not FinSight estimates."],
        tables=[
            ReportTable(
                caption="Saved DCF runs",
                kind="assumption",
                columns=["Name", "Saved", "WACC", "Terminal", "Value per share"],
                rows=rows,
            )
        ],
    )


def _ai(
    db: Session, owner: User, llm: LLMProvider | None, company: Company, max_sources: int
) -> ReportSection:
    title = "AI summary (cited)"
    if llm is None:
        return _unavailable(
            "ai", title, "AI summary not requested or the assistant is not configured"
        )
    try:
        result = research_service.ask(
            db, owner, llm, AI_QUESTION, company=company, document_ids=None, max_sources=max_sources
        )
    except AppError as exc:
        return _unavailable("ai", title, exc.message)
    text = "".join(
        s.text + "".join(f" [{c.source_index + 1}]" for c in s.citations)
        for s in result.grounded.segments
    )
    issues = [i.message for i in result.grounded.issues]
    return ReportSection(
        key="ai",
        title=title,
        paragraphs=[text, *(f"Note: {m}" for m in issues)],
        figures=[
            ReportFigure(
                label="Grounding",
                value=None,
                display=result.grounded.status.replace("_", " "),
                kind="ai_explanation",
                source=f"model {result.answer.model}",
            )
        ],
        tables=[
            ReportTable(
                caption="Sources cited by the summary",
                kind="ai_explanation",
                columns=["#", "Source"],
                rows=[[str(i + 1), s.title] for i, s in enumerate(result.sources)],
            )
        ],
    )


def generate(
    db: Session,
    owner: User,
    company: Company,
    *,
    provider: MarketDataProvider,
    cache: TTLCache,
    exchange: str | None,
    basis: ReportingBasis | None,
    llm: LLMProvider | None,
    title: str | None,
    stale_after_days: int,
    max_sources: int,
    today: date,
) -> ResearchReport:
    count = len(
        list(db.scalars(select(ResearchReport.id).where(ResearchReport.owner_id == owner.id)))
    )
    if count >= MAX_REPORTS_PER_USER:
        raise AppError("limit_exceeded", f"At most {MAX_REPORTS_PER_USER} reports", 409)
    try:
        chosen_basis: ReportingBasis | None = company_service.choose_basis(db, company, basis)
    except AppError:
        if basis is not None:
            raise
        chosen_basis = None

    sections = [_profile(company)]
    market, resolved_exchange = _market(
        provider, cache, company, exchange, stale_after_days=stale_after_days, today=today
    )
    sections.append(market)
    if chosen_basis is None:
        reason = "no financial statements stored; fetch statements first"
        sections += [
            _unavailable("financials", "Financial statements", reason),
            _unavailable("ratios", "Ratios", reason),
            _unavailable("valuation", "Valuation multiples", reason),
        ]
    else:
        sections += [
            _financials(db, company, chosen_basis),
            _ratios(db, company, chosen_basis),
            _valuation(
                db,
                provider,
                cache,
                company,
                resolved_exchange,
                chosen_basis,
                stale_after_days=stale_after_days,
                today=today,
            ),
        ]
    sections += [
        _actions(provider, cache, company),
        _documents(db, owner, company),
        _valuations(db, owner, company),
        _ai(db, owner, llm, company, max_sources),
    ]
    content = ReportContent(
        title=title or f"{company.name} — research report",
        generated_at=datetime.now(UTC),
        company=ReportCompany(
            market=company.market,
            ticker=company.ticker,
            name=company.name,
            isin=company.isin,
            listings=[
                f"{i.exchange}: {i.symbol}"
                for i in sorted(company.instruments, key=lambda i: i.exchange)
            ],
        ),
        exchange=resolved_exchange,
        basis=chosen_basis,
        sections=sections,
        disclaimers=DISCLAIMERS,
        engine_version=__version__,
    )
    report = ResearchReport(
        owner_id=owner.id,
        company_id=company.id,
        title=content.title[:200],
        ticker=company.ticker,
        includes_ai=llm is not None,
        content=content.model_dump(mode="json"),
        engine_version=__version__,
    )
    db.add(report)
    db.commit()
    return get_owned(db, owner, report.id)


def list_for(db: Session, owner: User) -> list[ResearchReport]:
    return list(
        db.scalars(
            select(ResearchReport)
            .where(ResearchReport.owner_id == owner.id)
            .order_by(ResearchReport.created_at.desc())
        )
    )


def get_owned(db: Session, owner: User, report_id: uuid.UUID) -> ResearchReport:
    report = db.scalar(
        select(ResearchReport).where(
            ResearchReport.id == report_id, ResearchReport.owner_id == owner.id
        )
    )
    if report is None:
        raise AppError("not_found", "Report not found", 404)
    return report


def delete(db: Session, owner: User, report_id: uuid.UUID) -> None:
    db.delete(get_owned(db, owner, report_id))
    db.commit()


def content_of(report: ResearchReport) -> ReportContent:
    return ReportContent.model_validate(report.content)
