class ProviderConfigError(Exception):
    """The selected provider cannot be built (e.g. optional dependency missing)."""


def build_market_provider(
    settings: Settings, demo: DemoMarketDataProvider | None = None
) -> MarketDataProvider:
    if settings.market_data_provider == "tej":
        return TejMarketDataProvider(timeout=settings.market_data_timeout_seconds)
    return demo or DemoMarketDataProvider()


def build_fundamentals_provider(
    settings: Settings, demo: DemoMarketDataProvider | None = None
) -> FundamentalsProvider | None:
    if settings.fundamentals_provider == "none":
        return None
    if settings.fundamentals_provider == "yfinance":
        if not yfinance_available():
            raise ProviderConfigError("yfinance is not installed (pip install -e '.[yfinance]')")
        return YFinanceFundamentalsProvider()
    return demo or DemoMarketDataProvider()
